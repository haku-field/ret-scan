const QUESTIONS_PER_AXIS = 4

function shuffle(array){

  return [...array].sort(
    () => Math.random() - 0.5
  )
}

function hasTagOverlap(
  question,
  selected
){

  return selected.some(item => {

    return item.tags.some(tag =>
      question.tags.includes(tag)
    )
  })
}

function hasToneOverlap(
  question,
  selected
){

  return selected.some(item =>
    item.tone === question.tone
  )
}

function pickWithoutOverlap(
  pool,
  count,
  existing = []
){

  const shuffled =
    shuffle(pool)

  const selected = [...existing]

  for(const question of shuffled){

    if(
      selected.length
      >= count + existing.length
    ){
      break
    }

    const tagOverlap =
      hasTagOverlap(
        question,
        selected
      )

    const toneOverlap =
      hasToneOverlap(
        question,
        selected
      )

    if(
      !tagOverlap
      && !toneOverlap
    ){

      selected.push(question)
    }
  }

  return selected.slice(existing.length)
}

function pickQuestions(pool){

  const normal =
    pool.filter(question =>
      question.rarity !== "rare"
    )

  const rare =
    pool.filter(question =>
      question.rarity === "rare"
    )

  const selected = []

  const normalPicked =
    pickWithoutOverlap(
      normal,
      QUESTIONS_PER_AXIS - 1
    )

  selected.push(...normalPicked)

  const useRare =
    Math.random() < 0.35

  if(
    useRare &&
    rare.length > 0
  ){

    const rarePicked =
      pickWithoutOverlap(
        rare,
        1,
        selected
      )

    selected.push(...rarePicked)
  }

  while(
    selected.length
    < QUESTIONS_PER_AXIS
  ){

    const remaining =
      shuffle(pool).filter(
        question =>
          !selected.includes(question)
      )

    if(
      remaining.length === 0
    ){
      break
    }

    selected.push(remaining[0])
  }

  return shuffle(selected)
}

function distributeQuestions(
  questions
){

  const shuffled =
    shuffle(questions)

  const result = []

  while(shuffled.length > 0){

    const last =
      result[result.length - 1]

    let index =
      shuffled.findIndex(question => {

        if(!last){
          return true
        }

        const tagOverlap =
          hasTagOverlap(
            question,
            [last]
          )

        const toneOverlap =
          question.tone
          === last.tone

        return (
          !tagOverlap
          && !toneOverlap
        )
      })

    if(index === -1){
      index = 0
    }

    result.push(
      shuffled.splice(index, 1)[0]
    )
  }

  return result
}

export function buildQuestionSet(){

  const result = []

  Object.entries(questionPools)
    .forEach(([axis, pool]) => {

      const picked =
        pickQuestions(pool)

      picked.forEach(question => {

        result.push({
          ...question,
          axis
        })
      })
    })

  return distributeQuestions(result)
}